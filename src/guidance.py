CRITICAL_CODES: frozenset[str] = frozenset(CRITICAL_RATIONALE)

_CRITICAL_ORDER = {c: i for i, c in enumerate(CRITICAL_RATIONALE)}


def _code_of(item: object) -> str:
    """소견 표현 세 가지(코드 문자열 · dict/행 · Finding 객체)에서 코드를 꺼낸다."""
    if isinstance(item, str):
        return item
    if isinstance(item, Mapping):
        return str(item.get("code") or "")
    return str(getattr(item, "code", "") or "")


def _as_items(findings: object) -> list:
    """DataFrame · 레코드 목록 · 코드 목록을 같은 모양(목록)으로. pandas 를 import 하지 않는다."""
    if findings is None:
        return []
    if hasattr(findings, "to_dict") and hasattr(findings, "columns"):     # pandas.DataFrame
        if "code" not in findings.columns:
            return []
        return findings.to_dict("records")
    if isinstance(findings, str | Mapping):
        return [findings]
    return list(findings) if isinstance(findings, Iterable) else []


def critical_findings(findings: object) -> list:
    """소견 중 중대 신호만, 무거운 순서로.

    Args:
        findings: 소견 DataFrame(`code` 컬럼), 레코드(dict) 목록, Finding 객체 목록,
            코드 문자열 목록 중 하나.

    Returns:
        입력 원소를 그대로 담은 목록(DataFrame 이면 행 dict). 중대 신호가 없으면 빈 목록.
    """
    items = [x for x in _as_items(findings) if _code_of(x) in CRITICAL_CODES]
    return sorted(items, key=lambda x: _CRITICAL_ORDER.get(_code_of(x), len(_CRITICAL_ORDER)))


def checklist(findings: object) -> list[dict]:
    """소견 → 중복 없는 확인 항목 목록. 입력 순서(=중요도 순서)를 유지한다.

    같은 확인 문장을 여러 소견이 가리키면(예: 뉴스 신규 유형 → 일반 보도 항목) 한 줄로
    합치고 관련 코드를 모두 남긴다.

    Returns:
        [{"check": str, "docs": list[str], "cadence": str | None, "codes": list[str]}]
    """
    out: list[dict] = []
    by_check: dict[str, dict] = {}
    for item in _as_items(findings):
        code = _code_of(item)
        entry = check_for(code)
        if entry is None:
            continue
        row = by_check.get(entry["check"])
        if row is None:
            row = {"check": entry["check"], "docs": list(entry.get("docs") or []),
                   "cadence": entry.get("cadence"), "codes": []}
            by_check[entry["check"]] = row
            out.append(row)
        if code not in row["codes"]:
            row["codes"].append(code)
    return out
