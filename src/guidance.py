def grade_code(grade: str | None) -> str | None:
    """FS1/FS2/FS3 또는 High/Medium/Low 를 FS 코드로. 모르는 값이면 None."""
    g = str(grade or "").strip()
    if g in GRADE_ACTIONS:
        return g
    return GRADE_FROM_RISK.get(g)


def grade_action(grade: str | None) -> str:
    """등급(두 표기 모두 허용) → 권고 처리 한 줄. 등급이 없으면 빈 문자열."""
    code = grade_code(grade)
    return GRADE_ACTIONS.get(code, "") if code else ""


