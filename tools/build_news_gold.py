def main() -> int:
    titles: list[tuple[str, str]] = []   # (brand, title)
    for f in sorted(glob.glob(str(ROOT / "data" / "raw" / "news" / "*.json"))):
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        for a in d.get("articles", []):
            titles.append((d["brand"], a.get("title", "")))

    rows, unmatched = [], []
    for frag, gold in LABELS:
        hit = [(b, t) for b, t in titles if frag in t]
        if not hit:
            unmatched.append(frag)
            continue
        b, t = hit[0]
        rows.append({"source": "real", "brand": b, "title": t, "gold": gold})

    for t, gold, note in SYNTHETIC:
        rows.append({"source": "synthetic", "brand": "테스트브랜드",
                     "title": f"테스트브랜드, {t}", "gold": gold, "note": note})

    DEST.parent.mkdir(parents=True, exist_ok=True)
    with open(DEST, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    real = sum(1 for r in rows if r["source"] == "real")
    print(f"정답셋 저장: {DEST}  (real {real} + synthetic {len(rows) - real} = {len(rows)}건)")
    from collections import Counter
    print("클래스 분포:", dict(Counter(r["gold"] for r in rows)))
    if unmatched:
        print(f"⚠️ 원문에서 찾지 못한 라벨 {len(unmatched)}건 (뉴스 재수집으로 제목이 바뀌었을 수 있음):")
        for u in unmatched:
            print("   -", u)
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
